def write_at_gate(path: str | Path | None = None) -> Path:
    """Write per-AT status. Default: ``output/at_gate.json`` under cwd."""
    from stewardsim.validate import evaluate_at_gate

    target = Path(path) if path is not None else Path("output") / _GATE_NAME
    target.parent.mkdir(parents=True, exist_ok=True)
    gate = evaluate_at_gate()
    target.write_text(
        json.dumps(gate, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return target


def _load_or_evaluate_gate() -> dict[str, str]:
    from stewardsim.validate import evaluate_at_gate

    path = Path("output") / _GATE_NAME
    if path.is_file():
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError):
            payload = None
        if isinstance(payload, dict):
            return {str(key): str(value) for key, value in payload.items()}
    return evaluate_at_gate()


def report(*, tier: int | None = None) -> None:
    """Emit a report or refuse. Tier 2/3 require AT-5 == pass."""
    requested = {tier} if tier is not None else {1, 2, 3}
    gate = _load_or_evaluate_gate()
    at5 = gate.get("AT-5", "not_run")
    if requested & {2, 3} and at5 != "pass":
        print(
            "GOAL §8 reporting gate: AT-5 is "
            f"{at5}; Tier 2/3 results may not be reported. "
            "Fixture directories are software proof, not a paper result.",
            file=sys.stderr,
        )
        raise SystemExit(1)
    print("Tier 1 analytic ledger only. Fixture directories are not a paper result.")
    for at_id in sorted(gate):
        print(f"{at_id}: {gate[at_id]}")
