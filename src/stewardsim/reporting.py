"""Generated ODD / TRACE skeletons and the GOAL §8 reporting gate.

``stewardsim odd`` and ``stewardsim trace`` list every registered
``Parameter.name``. Names come from the last in-process study run when
one exists, plus live Parameter fields on Policy, AdherenceModel,
Determinant, and Importation, plus fixture ``world.yaml`` Parameters
when those files are loadable. Adding a Parameter in code or fixtures
changes TRACE.

``stewardsim validate`` writes the AT ledger. ``stewardsim report``
refuses Tier 2/3 while AT-5 is not green. Fixture directories are
software proof, not a paper result.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, get_args, get_origin

import yaml

from stewardsim.importation import Importation
from stewardsim.params import Parameter
from stewardsim.pathogen import Determinant
from stewardsim.policy import AdherenceModel, Policy

_REGISTRY_TYPES = (Policy, AdherenceModel, Determinant, Importation)
_WORLD_NAME = "world.yaml"
_GATE_NAME = "at_gate.json"


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def _mentions_parameter(annotation: Any) -> bool:
    if annotation is Parameter:
        return True
    if annotation is None or annotation is type(None):
        return False
    if isinstance(annotation, str):
        return "Parameter" in annotation
    origin = get_origin(annotation)
    if origin is None:
        name = getattr(annotation, "__name__", "")
        if name == "Parameter":
            return True
        forward = getattr(annotation, "__forward_arg__", None)
        return isinstance(forward, str) and "Parameter" in forward
    return any(_mentions_parameter(arg) for arg in get_args(annotation))


def parameter_field_names(model_cls: type) -> tuple[str, ...]:
    """Parameter-typed field names on a live Pydantic model class."""
    fields = getattr(model_cls, "model_fields", None)
    if not fields:
        return ()
    names = [
        name
        for name, field in fields.items()
        if _mentions_parameter(getattr(field, "annotation", None))
    ]
    return tuple(names)


def parameter_names_from_mapping(obj: Any) -> tuple[str, ...]:
    """Collect ``Parameter.name`` values from a loaded mapping (e.g. YAML)."""
    found: list[str] = []
    if isinstance(obj, dict):
        name = obj.get("name")
        if (
            isinstance(name, str)
            and "provenance" in obj
            and "distribution" in obj
        ):
            found.append(name)
        for value in obj.values():
            found.extend(parameter_names_from_mapping(value))
    elif isinstance(obj, (list, tuple)):
        for item in obj:
            found.extend(parameter_names_from_mapping(item))
    return tuple(found)


def type_registry_parameter_names() -> tuple[str, ...]:
    names: list[str] = []
    for model in _REGISTRY_TYPES:
        names.extend(parameter_field_names(model))
    return tuple(dict.fromkeys(names))


def _fixture_world_paths() -> list[Path]:
    candidates = (
        _repo_root() / "tests" / "fixtures" / "shape" / _WORLD_NAME,
        Path.cwd() / "tests" / "fixtures" / "shape" / _WORLD_NAME,
    )
    found: list[Path] = []
    seen: set[Path] = set()
    for path in candidates:
        try:
            resolved = path.resolve()
        except OSError:
            continue
        if resolved in seen or not path.is_file():
            continue
        seen.add(resolved)
        found.append(path)
    return found


def fixture_parameter_names() -> tuple[str, ...]:
    names: list[str] = []
    for path in _fixture_world_paths():
        try:
            data = yaml.safe_load(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, yaml.YAMLError):
            continue
        names.extend(parameter_names_from_mapping(data))
    return tuple(dict.fromkeys(names))


def last_run_parameter_names() -> tuple[str, ...]:
    import stewardsim.runner as runner

    run = runner._LAST_RUN
    if run is None:
        return ()
    return tuple(param.name for param in run.parameters)


def registered_parameter_names() -> tuple[str, ...]:
    """Last-run names if present, then live type + fixture registries."""
    names: list[str] = []
    names.extend(last_run_parameter_names())
    names.extend(type_registry_parameter_names())
    names.extend(fixture_parameter_names())
    return tuple(dict.fromkeys(names))


